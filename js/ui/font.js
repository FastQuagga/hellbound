// Неизвестный глиф — пустой квадрат.
const FALLBACK = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'];

// Типографские варианты приводятся к базовым глифам (строки из §22 содержат
// «—» и «·» — без алиасов они выводились бы пустыми квадратами).
const ALIASES = {
  '—': '-', '–': '-', '−': '-',
  '·': '.', '•': '.',
  '’': "'", '‘': "'",
  '“': '"', '”': '"', '„': '"',
};

// ── Нормализация символов ────────────────────────────────────────────────────
// NORM: код символа (charCodeAt) -> канонический символ глифа. Заполняется
// один раз при инициализации модуля: прописные, их строчные формы и
// типографские алиасы. В кадровом цикле не нужны ни toUpperCase, ни
// строковые конкатенации — только NORM.get(code).

const NORM = new Map();
for (const key of Object.keys(G)) {
  NORM.set(key.charCodeAt(0), key);
  const lower = key.toLowerCase();
  if (lower !== key && lower.length === 1) NORM.set(lower.charCodeAt(0), key);
}
for (const ch of Object.keys(ALIASES)) {
  NORM.set(ch.charCodeAt(0), ALIASES[ch]);
}

const UNKNOWN = '\uFFFD'; // канонический ключ неизвестного глифа (FALLBACK)

// ── Кэш отрисованных глифов ──────────────────────────────────────────────────
// Двухуровневый: стиль 'цвет\u0001масштаб' -> Map(символ -> мини-канвас).
// Ключ стиля строится один раз на вызов drawText (с мемоизацией последнего
// стиля), по символам — Map.get без конкатенаций: на кэш-попадании drawText
// в кадровом цикле не аллоцирует.

const styleCaches = new Map();
const CACHE_LIMIT = 4096; // суммарно глифов; защита от безграничного роста
let cacheCount = 0;
let lastColor = null;
let lastScale = 0;
let lastStyle = null;

function getStyleCache(color, scale) {
  if (color === lastColor && scale === lastScale && lastStyle !== null) {
    return lastStyle;
  }
  if (cacheCount >= CACHE_LIMIT) {
    styleCaches.clear();
    cacheCount = 0;
  }
  const key = color + '\u0001' + scale;
  let style = styleCaches.get(key);
  if (style === undefined) {
    style = new Map();
    styleCaches.set(key, style);
  }
  lastColor = color;
  lastScale = scale;
  lastStyle = style;
  return style;
}

function renderGlyph(style, ch, color, scale) {
  const rows = G[ch] || FALLBACK;
  const glyph = document.createElement('canvas');
  glyph.width = Math.max(1, Math.ceil(GLYPH_W * scale));
  glyph.height = Math.max(1, Math.ceil(FONT_H * scale));
  const g = glyph.getContext('2d');
  g.fillStyle = color;
  for (let r = 0; r < FONT_H; r++) {
    const row = rows[r];
    for (let c = 0; c < GLYPH_W; c++) {
      if (row.charCodeAt(c) === 35 /* '#' */) {
        g.fillRect(c * scale, r * scale, scale, scale);
      }
    }
  }
  style.set(ch, glyph);
  cacheCount++;
  return glyph;
}

// ── Публичный API ────────────────────────────────────────────────────────────

// Ширина текста в пикселях (моноширинный шрифт: 5px глиф + 1px интервал).
export function textWidth(text, scale = 1) {
  if (text == null) return 0;
  const n = String(text).length;
  return n === 0 ? 0 : (n * ADVANCE - SPACING) * scale;
}

// Рисует строку. opts: { scale=1, color='#fff', align='left'|'center'|'right', alpha=1 }.
// (x, y) — левый верх строки; при align 'center'/'right' x — центр/правый край.
export function drawText(ctx, text, x, y, opts = {}) {
  if (!ctx || text == null) return;
  const str = String(text);
  if (str.length === 0) return;

  let scale = +opts.scale;
  if (!Number.isFinite(scale) || scale <= 0) scale = 1;
  const color = typeof opts.color === 'string' ? opts.color : '#fff';
  let alpha = opts.alpha == null ? 1 : +opts.alpha;
  if (!Number.isFinite(alpha)) alpha = 1;
  if (alpha <= 0) return;
  if (alpha > 1) alpha = 1;

  let penX = x;
  if (opts.align === 'center') penX -= textWidth(str, scale) / 2;
  else if (opts.align === 'right') penX -= textWidth(str, scale);
  const top = Math.round(y);
  const step = ADVANCE * scale;

  const style = getStyleCache(color, scale);
  const prevAlpha = ctx.globalAlpha;
  if (alpha < 1) ctx.globalAlpha = prevAlpha * alpha;
  for (let i = 0; i < str.length; i++) {
    let ch = NORM.get(str.charCodeAt(i));
    if (ch === undefined) ch = UNKNOWN;
    if (ch !== ' ') {
      let glyph = style.get(ch);
      if (glyph === undefined) glyph = renderGlyph(style, ch, color, scale);
      ctx.drawImage(glyph, Math.round(penX), top);
    }
    penX += step;
  }
  if (alpha < 1) ctx.globalAlpha = prevAlpha;
}
